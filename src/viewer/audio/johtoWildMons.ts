/**
 * Selecciona una especie salvaje característica para el mapa exterior de Johto.
 * Distribución canónica: 80% Pokémon terrestres / 20% acuáticos en mapas con ambos hábitats.
 */
export function getJohtoWildMon(mapId: string, isWaterMon?: { value: boolean }): number {
  if (isWaterMon) isWaterMon.value = false;
  const pool = JOHTO_WILD_MONS[mapId];
  if (!pool) {
    const fallbackLand = [C.SPECIES_PIDGEY, C.SPECIES_SENTRET, C.SPECIES_RATTATA];
    return fallbackLand[Math.floor(Math.random() * fallbackLand.length)];
  }

  const hasLand = Boolean(pool.land && pool.land.length > 0);
  const hasWater = Boolean(pool.water && pool.water.length > 0);

  if (!hasLand && !hasWater) return C.SPECIES_NONE;

  if (hasLand && !hasWater) {
    return pool.land![Math.floor(Math.random() * pool.land!.length)];
  }

  if (!hasLand && hasWater) {
    if (isWaterMon) isWaterMon.value = true;
    return pool.water![Math.floor(Math.random() * pool.water!.length)];
  }

  // 80% tierra / 20% agua
  if (Math.random() < 0.8) {
    return pool.land![Math.floor(Math.random() * pool.land!.length)];
  } else {
    if (isWaterMon) isWaterMon.value = true;
    return pool.water![Math.floor(Math.random() * pool.water!.length)];
  }
}
