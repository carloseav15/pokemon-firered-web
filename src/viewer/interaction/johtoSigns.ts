export function getJohtoSign(mapId: string, lx: number, ly: number, scriptName?: string): JohtoSignInfo | null {
  const coordKey = `${mapId}:${lx},${ly}`;
  const rawText = JOHTO_COORD_SIGNS[coordKey] ?? (scriptName ? JOHTO_SCRIPT_SIGNS[scriptName] : undefined);
  if (!rawText) return null;
  const title = formatSignTitle(mapId, scriptName);
  return { title, text: rawText };
}
