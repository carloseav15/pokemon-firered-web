// pokeemerald src/wild_encounter.c: standard land/water encounters, Sweet Scent, Rock Smash, the local
// wild mon helpers, the Repel counter and the lead-ability effects (Magnet Pull, Static, Hustle/
// Vital Spirit/Pressure, Synchronize, Cute Charm, Keen Eye/Intimidate, Stench/Illuminate/White Smoke/
// Arena Trap/Sand Veil). Runs on the Emerald export (cdata "wild_encounter", DATA_ROOT "/emerald") and
// the Hoenn bank (EM flag/var IDs). The battle is started on the FireRed engine (BattleSetup_StartWildBattle).
//
// Not ported here (rejected when reached, never approximated): fishing (FishingWildEncounter, Feebas
// spots: fishing.c and dewford trends), Battle Pike and Battle Pyramid wild headers, roamer battles
// (roamer.c) and Safari Zone Pokéblock natures. Mass outbreaks (tv.c) and the roamer are read from
// their SaveBlock1 fields, which nothing in the port sets yet (ClearSav1 values).
import type { Game } from "@game/game";
import { cdata, type SymRef } from "@core/hw/assets";
import { random, random32 } from "@core/random";
import { rom } from "@core/rom";
import { flagGet, save, varGet, varSet } from "@game/save";
import { createMon, genderFromPersonality, MON_FEMALE, MON_GENDERLESS, MON_MALE, setMoveSlot, type Pokemon } from "@core/pokemon/pokemon";
import { GetMonAbility } from "@core/pokemon/mon_extra";
import * as EM from "./generated/constants";
import * as EMB from "./generated/metatileBehavior";
import { save as emSave } from "./save";

export const MAX_ENCOUNTER_RATE = 2880;
export const HEADER_NONE = 0xffff;
const NUM_ALTERING_CAVE_TABLES = 9;

export const WILD_AREA_LAND = 0;
export const WILD_AREA_WATER = 1;
export const WILD_AREA_ROCKS = 2;

export const WILD_CHECK_REPEL = 1 << 0;
export const WILD_CHECK_KEEN_EYE = 1 << 1;

export type WildPokemon = { minLevel: number; maxLevel: number; species: number };
export type WildPokemonInfo = { encounterRate: number; wildPokemon: SymRef };
export type WildPokemonHeader = { mapGroup: number; mapNum: number; landMonsInfo: SymRef | 0; waterMonsInfo: SymRef | 0; rockSmashMonsInfo: SymRef | 0; fishingMonsInfo: SymRef | 0 };

const data = <T>(name: string): T => cdata<T>("wild_encounter", name);
const info = (ref: SymRef | 0): WildPokemonInfo | null => ref ? data<WildPokemonInfo>(ref.$sym) : null;
const mons = (wildMonInfo: WildPokemonInfo): WildPokemon[] => data<WildPokemon[]>(wildMonInfo.wildPokemon.$sym);

let sWildEncountersDisabled = false;
let sGame: Game | null = null;
/** gEnemyParty[0] as written by CreateWildMon. */
let sWildMon: Pokemon | null = null;

export function setEmeraldWildEncounterGame(game: Game): void { sGame = game; }
export function lastGeneratedWildMon(): Pokemon | null { return sWildMon; }

/** DisableWildEncounters */
export function DisableWildEncounters(disabled: boolean): void {
  sWildEncountersDisabled = disabled;
}

/**
 * ENCOUNTER_CHANCE_<TYPE>_SLOT_n of include/constants/wild_encounter.h, generated by
 * src/data/wild_encounters.constants.json.txt as running sums of the gWildMonHeaders field
 * `encounter_rates` (exported unchanged in data/wild.json "rates").
 */
function encounterChanceSlots(type: "land_mons" | "water_mons"): number[] {
  const rates = rom.wild.rates[type];
  if (!rates) throw Error(`wild.json has no ${type} encounter rates`);
  const slots: number[] = [];
  for (const rate of rates) slots.push((slots.at(-1) ?? 0) + rate);
  return slots;
}

/** ChooseWildMonIndex_Land: NUM_LAND_MONS_ENCOUNTER_SLOTS. */
export function ChooseWildMonIndex_Land(): number {
  const slots = encounterChanceSlots("land_mons");
  const rand = (random() % slots.at(-1)!) & 0xff;
  for (let i = 0; i < slots.length - 1; i++) if (rand < slots[i]) return i;
  return slots.length - 1;
}

/** ChooseWildMonIndex_WaterRock: NUM_ROCK_SMASH_MONS_ENCOUNTER_SLOTS / NUM_WATER_MONS_ENCOUNTER_SLOTS. */
export function ChooseWildMonIndex_WaterRock(): number {
  const slots = encounterChanceSlots("water_mons");
  const rand = (random() % slots.at(-1)!) & 0xff;
  for (let i = 0; i < slots.length - 1; i++) if (rand < slots[i]) return i;
  return slots.length - 1;
}

const leadIsEgg = (): boolean => save.party[0]?.isEgg ?? true;
const leadAbility = (): number => GetMonAbility(save.party[0]!);

/** ChooseWildMonLevel (u8 arithmetic). */
export function ChooseWildMonLevel(wildPokemon: WildPokemon): number {
  let min: number, max: number;
  if (wildPokemon.maxLevel >= wildPokemon.minLevel) { min = wildPokemon.minLevel; max = wildPokemon.maxLevel; }
  else { min = wildPokemon.maxLevel; max = wildPokemon.minLevel; }
  const range = (max - min + 1) & 0xff;
  let rand = (random() % range) & 0xff;
  // check ability for max level mon
  if (!leadIsEgg()) {
    const ability = leadAbility();
    if (ability === EM.ABILITY_HUSTLE || ability === EM.ABILITY_VITAL_SPIRIT || ability === EM.ABILITY_PRESSURE) {
      if (random() % 2 === 0) return max;
      if (rand !== 0) rand--;
    }
  }
  return (min + rand) & 0xff;
}

/** GetCurrentMapWildMonHeaderId */
export function GetCurrentMapWildMonHeaderId(): number {
  const headers = data<WildPokemonHeader[]>("gWildMonHeaders");
  for (let i = 0; ; i++) {
    const wildHeader = headers[i];
    if (!wildHeader || wildHeader.mapGroup === (EM.MAP_UNDEFINED >> 8)) break;
    if (wildHeader.mapGroup === save.location.mapGroup && wildHeader.mapNum === save.location.mapNum) {
      if (save.location.mapGroup === (EM.MAP_ALTERING_CAVE >> 8) && save.location.mapNum === (EM.MAP_ALTERING_CAVE & 0xff)) {
        let alteringCaveId = varGet(EM.VAR_ALTERING_CAVE_WILD_SET);
        if (alteringCaveId >= NUM_ALTERING_CAVE_TABLES) alteringCaveId = 0;
        i += alteringCaveId;
      }
      return i;
    }
  }
  return HEADER_NONE;
}

/** PickWildMonNature */
function PickWildMonNature(): number {
  if (flagGet(EM.FLAG_SYS_SAFARI_MODE) && random() % 100 < 80)
    throw Error("pokeemerald Safari Zone Pokéblock natures (SafariZoneGetActivePokeblock) are not ported");
  // check synchronize for a Pokémon with the same ability
  if (!leadIsEgg() && leadAbility() === EM.ABILITY_SYNCHRONIZE && random() % 2 === 0)
    return (save.party[0]!.personality >>> 0) % EM.NUM_NATURES;
  // random nature
  return random() % EM.NUM_NATURES;
}

/** pokemon.c CreateMonWithNature / CreateMonWithGenderNatureLetter (no Unown letter), USE_RANDOM_IVS, OT_ID_PLAYER_ID. */
function createWildMonWith(species: number, level: number, nature: number, gender?: number): Pokemon {
  let personality: number;
  do personality = random32() >>> 0;
  while (personality % EM.NUM_NATURES !== nature || (gender !== undefined && genderFromPersonality(species, personality) !== gender));
  return createMon(species, level, { personality, metLocation: sGame?.overworld.header.regionMapSection });
}

/** CreateWildMon: ZeroEnemyPartyMons, then gEnemyParty[0]. */
function CreateWildMon(species: number, level: number): void {
  sWildMon = null;
  let checkCuteCharm = true;
  switch (rom.species[species]!.genderRatio) {
    case MON_MALE:
    case MON_FEMALE:
    case MON_GENDERLESS:
      checkCuteCharm = false;
      break;
  }
  if (checkCuteCharm && !leadIsEgg() && leadAbility() === EM.ABILITY_CUTE_CHARM && random() % 3 !== 0) {
    const lead = save.party[0]!;
    // misses mon is genderless check, although no genderless mon can have cute charm as ability
    const gender = genderFromPersonality(lead.species, lead.personality) === MON_FEMALE ? MON_MALE : MON_FEMALE;
    sWildMon = createWildMonWith(species, level, PickWildMonNature(), gender);
    return;
  }
  sWildMon = createWildMonWith(species, level, PickWildMonNature());
}

/** TryGetRandomWildMonIndexByType (variable-length validIndexes). */
function TryGetRandomWildMonIndexByType(wildMon: WildPokemon[], type: number, numMon: number, monIndex: { value: number }): boolean {
  const validIndexes: number[] = [];
  for (let i = 0; i < numMon; i++) {
    const types = rom.species[wildMon[i]!.species]!.types;
    if (types[0] === type || types[1] === type) validIndexes.push(i);
  }
  if (validIndexes.length === 0 || validIndexes.length === numMon) return false;
  monIndex.value = validIndexes[random() % validIndexes.length]!;
  return true;
}

/**
 * TryGetAbilityInfluencedWildMonIndex, without BUGFIX: the type scan always covers
 * NUM_LAND_MONS_ENCOUNTER_SLOTS entries, also for the 5-entry water table (the C reads past it).
 */
function TryGetAbilityInfluencedWildMonIndex(wildMon: WildPokemon[], type: number, ability: number, monIndex: { value: number }): boolean {
  if (leadIsEgg()) return false;
  if (leadAbility() !== ability) return false;
  if (random() % 2 !== 0) return false;
  const numLandSlots = encounterChanceSlots("land_mons").length;
  if (wildMon.length < numLandSlots) throw Error("TryGetAbilityInfluencedWildMonIndex reads past a table shorter than the land table (pokeemerald bug, no data to read here)");
  return TryGetRandomWildMonIndexByType(wildMon, type, numLandSlots, monIndex);
}

/** IsWildLevelAllowedByRepel */
export function IsWildLevelAllowedByRepel(wildLevel: number): boolean {
  if (!varGet(EM.VAR_REPEL_STEP_COUNT)) return true;
  for (const mon of save.party) {
    if (mon.hp && !mon.isEgg) return !(wildLevel < mon.level);
  }
  return false;
}

/** IsAbilityAllowingEncounter */
function IsAbilityAllowingEncounter(level: number): boolean {
  if (leadIsEgg()) return true;
  const ability = leadAbility();
  if (ability === EM.ABILITY_KEEN_EYE || ability === EM.ABILITY_INTIMIDATE) {
    const playerMonLevel = save.party[0]!.level;
    if (playerMonLevel > 5 && level <= playerMonLevel - 5 && !(random() % 2)) return false;
  }
  return true;
}

/** TryGenerateWildMon */
export function TryGenerateWildMon(wildMonInfo: WildPokemonInfo, area: number, flags: number): boolean {
  const wildPokemon = mons(wildMonInfo);
  const index = { value: 0 };
  switch (area) {
    case WILD_AREA_LAND:
      if (TryGetAbilityInfluencedWildMonIndex(wildPokemon, EM.TYPE_STEEL, EM.ABILITY_MAGNET_PULL, index)) break;
      if (TryGetAbilityInfluencedWildMonIndex(wildPokemon, EM.TYPE_ELECTRIC, EM.ABILITY_STATIC, index)) break;
      index.value = ChooseWildMonIndex_Land();
      break;
    case WILD_AREA_WATER:
      if (TryGetAbilityInfluencedWildMonIndex(wildPokemon, EM.TYPE_ELECTRIC, EM.ABILITY_STATIC, index)) break;
      index.value = ChooseWildMonIndex_WaterRock();
      break;
    case WILD_AREA_ROCKS:
      index.value = ChooseWildMonIndex_WaterRock();
      break;
  }
  const level = ChooseWildMonLevel(wildPokemon[index.value]!);
  if (flags & WILD_CHECK_REPEL && !IsWildLevelAllowedByRepel(level)) return false;
  if (save.mapLayoutId !== EM.LAYOUT_BATTLE_FRONTIER_BATTLE_PIKE_ROOM_WILD_MONS && flags & WILD_CHECK_KEEN_EYE && !IsAbilityAllowingEncounter(level)) return false;
  CreateWildMon(wildPokemon[index.value]!.species, level);
  return true;
}

/** SetUpMassOutbreakEncounter */
function SetUpMassOutbreakEncounter(flags: number): boolean {
  const outbreak = emSave.outbreak;
  if (flags & WILD_CHECK_REPEL && !IsWildLevelAllowedByRepel(outbreak.level)) return false;
  CreateWildMon(outbreak.species, outbreak.level);
  for (let i = 0; i < EM.MAX_MON_MOVES; i++) setMoveSlot(sWildMon!, outbreak.moves[i]!, i);
  return true;
}

/** DoMassOutbreakEncounterTest */
function DoMassOutbreakEncounterTest(): boolean {
  const outbreak = emSave.outbreak;
  if (outbreak.species !== EM.SPECIES_NONE && save.location.mapNum === outbreak.locationMapNum && save.location.mapGroup === outbreak.locationMapGroup)
    return random() % 100 < outbreak.probability;
  return false;
}

/** roamer.c TryStartRoamerEncounter: IsRoamerAt needs an active roamer (SaveBlock1.roamer.active). */
function TryStartRoamerEncounter(): boolean {
  if (!emSave.roamer.active) return false;
  throw Error("pokeemerald roamer encounters (roamer.c) are not ported");
}

/** EncounterOddsCheck */
function EncounterOddsCheck(encounterRate: number): boolean {
  return random() % MAX_ENCOUNTER_RATE < encounterRate;
}

/** ApplyFluteEncounterRateMod */
function ApplyFluteEncounterRateMod(encRate: number): number {
  if (flagGet(EM.FLAG_SYS_ENC_UP_ITEM)) return encRate + Math.trunc(encRate / 2);
  if (flagGet(EM.FLAG_SYS_ENC_DOWN_ITEM)) return Math.trunc(encRate / 2);
  return encRate;
}

/** ApplyCleanseTagEncounterRateMod */
function ApplyCleanseTagEncounterRateMod(encRate: number): number {
  if (save.party[0]?.heldItem === EM.ITEM_CLEANSE_TAG) return Math.trunc(encRate * 2 / 3);
  return encRate;
}

/** WildEncounterCheck: returns true if it will try to create a wild encounter. */
function WildEncounterCheck(baseRate: number, ignoreAbility: boolean): boolean {
  let encounterRate = baseRate * 16;
  if ((sGame?.overworld.player.flags ?? 0) & (EM.PLAYER_AVATAR_FLAG_MACH_BIKE | EM.PLAYER_AVATAR_FLAG_ACRO_BIKE))
    encounterRate = Math.trunc(encounterRate * 80 / 100);
  encounterRate = ApplyFluteEncounterRateMod(encounterRate);
  encounterRate = ApplyCleanseTagEncounterRateMod(encounterRate);
  if (!ignoreAbility && !leadIsEgg()) {
    const ability = leadAbility();
    if (ability === EM.ABILITY_STENCH && save.mapLayoutId === EM.LAYOUT_BATTLE_FRONTIER_BATTLE_PYRAMID_FLOOR) encounterRate = Math.trunc(encounterRate * 3 / 4);
    else if (ability === EM.ABILITY_STENCH) encounterRate = Math.trunc(encounterRate / 2);
    else if (ability === EM.ABILITY_ILLUMINATE) encounterRate *= 2;
    else if (ability === EM.ABILITY_WHITE_SMOKE) encounterRate = Math.trunc(encounterRate / 2);
    else if (ability === EM.ABILITY_ARENA_TRAP) encounterRate *= 2;
    else if (ability === EM.ABILITY_SAND_VEIL && save.weather === EM.WEATHER_SANDSTORM) encounterRate = Math.trunc(encounterRate / 2);
  }
  if (encounterRate > MAX_ENCOUNTER_RATE) encounterRate = MAX_ENCOUNTER_RATE;
  return EncounterOddsCheck(encounterRate);
}

/** AllowWildCheckOnNewMetatile: 40% of the first steps on a different metatile behavior skip the check. */
function AllowWildCheckOnNewMetatile(): boolean {
  return !(random() % 100 >= 60);
}

/** AreLegendariesInSootopolisPreventingEncounters */
function AreLegendariesInSootopolisPreventingEncounters(): boolean {
  if (save.location.mapGroup !== (EM.MAP_SOOTOPOLIS_CITY >> 8) || save.location.mapNum !== (EM.MAP_SOOTOPOLIS_CITY & 0xff)) return false;
  return flagGet(EM.FLAG_LEGENDARIES_IN_SOOTOPOLIS);
}

function rejectFrontierLayouts(): void {
  if (save.mapLayoutId === EM.LAYOUT_BATTLE_FRONTIER_BATTLE_PIKE_ROOM_WILD_MONS || save.mapLayoutId === EM.LAYOUT_BATTLE_FRONTIER_BATTLE_PYRAMID_FLOOR)
    throw Error("pokeemerald Battle Pike / Battle Pyramid wild encounters are not ported");
}

function startWildBattle(): void {
  if (!sGame || !sWildMon) throw Error("Emerald wild encounter without an engine game");
  sGame.battleSetup.StartWildBattle(sWildMon);
}

/** StandardWildEncounter */
export function StandardWildEncounter(curMetatileBehavior: number, prevMetatileBehavior: number): boolean {
  if (sWildEncountersDisabled) return false;
  const headerId = GetCurrentMapWildMonHeaderId();
  if (headerId === HEADER_NONE) {
    rejectFrontierLayouts();
    return false;
  }
  const header = data<WildPokemonHeader[]>("gWildMonHeaders")[headerId]!;
  const surfing = ((sGame?.overworld.player.flags ?? 0) & EM.PLAYER_AVATAR_FLAG_SURFING) !== 0;
  if (EMB.MetatileBehavior_IsLandWildEncounter(curMetatileBehavior)) {
    const land = info(header.landMonsInfo);
    if (!land) return false;
    if (prevMetatileBehavior !== curMetatileBehavior && !AllowWildCheckOnNewMetatile()) return false;
    if (!WildEncounterCheck(land.encounterRate, false)) return false;
    if (TryStartRoamerEncounter()) return false;
    if (DoMassOutbreakEncounterTest() && SetUpMassOutbreakEncounter(WILD_CHECK_REPEL | WILD_CHECK_KEEN_EYE)) {
      startWildBattle();
      return true;
    }
    // try a regular wild land encounter
    if (TryGenerateWildMon(land, WILD_AREA_LAND, WILD_CHECK_REPEL | WILD_CHECK_KEEN_EYE)) {
      startWildBattle();
      return true;
    }
    return false;
  }
  if (EMB.MetatileBehavior_IsWaterWildEncounter(curMetatileBehavior) || (surfing && EMB.MetatileBehavior_IsBridgeOverWater(curMetatileBehavior))) {
    if (AreLegendariesInSootopolisPreventingEncounters()) return false;
    const water = info(header.waterMonsInfo);
    if (!water) return false;
    if (prevMetatileBehavior !== curMetatileBehavior && !AllowWildCheckOnNewMetatile()) return false;
    if (!WildEncounterCheck(water.encounterRate, false)) return false;
    if (TryStartRoamerEncounter()) return false;
    // try a regular surfing encounter
    if (TryGenerateWildMon(water, WILD_AREA_WATER, WILD_CHECK_REPEL | WILD_CHECK_KEEN_EYE)) {
      startWildBattle();
      return true;
    }
    return false;
  }
  return false;
}

/** RockSmashWildEncounter: gSpecialVar_Result. */
export function RockSmashWildEncounter(): void {
  const headerId = GetCurrentMapWildMonHeaderId();
  if (headerId === HEADER_NONE) { varSet(EM.VAR_RESULT, 0); return; }
  const rocks = info(data<WildPokemonHeader[]>("gWildMonHeaders")[headerId]!.rockSmashMonsInfo);
  if (!rocks) varSet(EM.VAR_RESULT, 0);
  else if (WildEncounterCheck(rocks.encounterRate, true) && TryGenerateWildMon(rocks, WILD_AREA_ROCKS, WILD_CHECK_REPEL | WILD_CHECK_KEEN_EYE)) {
    startWildBattle();
    varSet(EM.VAR_RESULT, 1);
  } else varSet(EM.VAR_RESULT, 0);
}

/** SweetScentWildEncounter; `behavior` is MapGridGetMetatileBehaviorAt(PlayerGetDestCoords). */
export function SweetScentWildEncounter(behavior: number): boolean {
  const headerId = GetCurrentMapWildMonHeaderId();
  if (headerId === HEADER_NONE) {
    rejectFrontierLayouts();
    return false;
  }
  const header = data<WildPokemonHeader[]>("gWildMonHeaders")[headerId]!;
  if (EMB.MetatileBehavior_IsLandWildEncounter(behavior)) {
    const land = info(header.landMonsInfo);
    if (!land) return false;
    if (TryStartRoamerEncounter()) return false;
    if (DoMassOutbreakEncounterTest()) SetUpMassOutbreakEncounter(0);
    else TryGenerateWildMon(land, WILD_AREA_LAND, 0);
    startWildBattle();
    return true;
  }
  if (EMB.MetatileBehavior_IsWaterWildEncounter(behavior)) {
    if (AreLegendariesInSootopolisPreventingEncounters()) return false;
    const water = info(header.waterMonsInfo);
    if (!water) return false;
    if (TryStartRoamerEncounter()) return false;
    TryGenerateWildMon(water, WILD_AREA_WATER, 0);
    startWildBattle();
    return true;
  }
  return false;
}

/** DoesCurrentMapHaveFishingMons */
export function DoesCurrentMapHaveFishingMons(): boolean {
  const headerId = GetCurrentMapWildMonHeaderId();
  return headerId !== HEADER_NONE && !!data<WildPokemonHeader[]>("gWildMonHeaders")[headerId]!.fishingMonsInfo;
}

/** GetLocalWildMon */
export function GetLocalWildMon(isWaterMon: { value: boolean }): number {
  isWaterMon.value = false;
  const headerId = GetCurrentMapWildMonHeaderId();
  if (headerId === HEADER_NONE) return EM.SPECIES_NONE;
  const header = data<WildPokemonHeader[]>("gWildMonHeaders")[headerId]!;
  const land = info(header.landMonsInfo), water = info(header.waterMonsInfo);
  // Neither
  if (!land && !water) return EM.SPECIES_NONE;
  // Land Pokémon
  if (land && !water) return mons(land)[ChooseWildMonIndex_Land()]!.species;
  // Water Pokémon
  if (!land && water) {
    isWaterMon.value = true;
    return mons(water)[ChooseWildMonIndex_WaterRock()]!.species;
  }
  // Either land or water Pokémon
  if (random() % 100 < 80) return mons(land!)[ChooseWildMonIndex_Land()]!.species;
  isWaterMon.value = true;
  return mons(water!)[ChooseWildMonIndex_WaterRock()]!.species;
}

/** GetLocalWaterMon */
export function GetLocalWaterMon(): number {
  const headerId = GetCurrentMapWildMonHeaderId();
  if (headerId !== HEADER_NONE) {
    const water = info(data<WildPokemonHeader[]>("gWildMonHeaders")[headerId]!.waterMonsInfo);
    if (water) return mons(water)[ChooseWildMonIndex_WaterRock()]!.species;
  }
  return EM.SPECIES_NONE;
}

/**
 * UpdateRepelCounter. InBattlePike / CurrentBattlePyramidLocation / InUnionRoom are FALSE outside
 * those facilities, which the Hoenn port does not enter (their layouts are rejected above).
 * Returns the EventScript_RepelWoreOff pointer to set up when the Repel wore off.
 */
export function UpdateRepelCounter(): number {
  let steps = varGet(EM.VAR_REPEL_STEP_COUNT);
  if (steps !== 0) {
    steps--;
    varSet(EM.VAR_REPEL_STEP_COUNT, steps);
    if (steps === 0) return rom.label("EventScript_RepelWoreOff");
  }
  return 0;
}
