/** Built on first use: the command modules import each other (and the engine) circularly. */
function build(): Array<() => void> {
  const all = { ...part1, ...part2, ...part3, ...part4 } as unknown as Record<string, () => void>;
  return NAMES.map((n) => {
    const fn = all[n];
    if (!fn) throw new Error(`battle command missing: ${n}`);
    return fn;
  });
}

