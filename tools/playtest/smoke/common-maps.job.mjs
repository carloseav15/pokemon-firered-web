import assert from 'node:assert/strict';
// Real UI/source data. No injected map coordinates, fabricated collisions or game state.
export default async function run(ctx) {
  const p = ctx.page, base = process.env.PW_BASE ?? 'http://localhost:5174/';
  await p.setViewportSize({ width: 1280, height: 800 });
  const requests = [];
  p.on('request', r => requests.push(new URL(r.url()).pathname));
  await p.goto(new URL('maps.html?game=firered', base).href);
  await p.locator('#source').filter({ hasText: 'FireRed' }).waitFor();
  await p.waitForFunction(() => document.querySelectorAll('#stage img').length > 0);
  await p.locator('#search').fill('Pallet Town');
  await p.locator('#list a[href="#mapa=MAP_PALLET_TOWN"]').click();
  await p.locator('#meta').filter({ hasText: 'MAP_PALLET_TOWN' }).waitFor();
  await p.locator('#detail .links a').filter({ hasText: 'Professor Oaks Lab' }).click();
  await p.locator('#meta').filter({ hasText: 'MAP_PALLET_TOWN_PROFESSOR_OAKS_LAB' }).waitFor();
  await p.locator('#back').click();
  await p.locator('#meta').filter({ hasText: 'MAP_PALLET_TOWN' }).waitFor();
  await p.locator('#world-btn').click();
  await p.locator('#meta').filter({ hasText: '37 mapas conectados' }).waitFor();
  await p.locator('#zoom').selectOption('0.25');
  await p.waitForFunction(() => document.querySelector('#stage img')?.src.includes('overview'));
  await p.locator('#zoom').selectOption('1');
  await p.waitForFunction(() => !document.querySelector('#stage img')?.src.includes('overview'));
  const before = await p.locator('#viewport').evaluate(el => ({ x: el.scrollLeft, y: el.scrollTop }));
  const box = await p.locator('#viewport').boundingBox();
  await p.mouse.move(box.x + box.width / 2, box.y + box.height / 2);
  await p.mouse.down(); await p.mouse.move(box.x + box.width / 2 - 90, box.y + box.height / 2 - 80, { steps: 8 }); await p.mouse.up();
  const after = await p.locator('#viewport').evaluate(el => ({ x: el.scrollLeft, y: el.scrollTop }));
  assert(after.x > before.x || after.y > before.y, 'camera drag failed');
  const knownPosition = after;
  await p.locator('#game').selectOption('emerald');
  await p.locator('#source').filter({ hasText: 'Emerald' }).waitFor();
  await p.locator('#search').fill('Littleroot Town');
  await p.locator('#list a[href="#mapa=MAP_LITTLEROOT_TOWN"]').click();
  await p.locator('#meta').filter({ hasText: 'MAP_LITTLEROOT_TOWN' }).waitFor();
  assert(await p.locator('#explore').isVisible());
  await p.locator('#game').selectOption('hns');
  await p.locator('#source').filter({ hasText: 'Heart & Soul' }).waitFor();
  assert(!(await p.locator('#explore').isVisible()));
  await p.locator('#filter').selectOption('all'); await p.locator('#search').fill('Route7');
  await p.locator('#list a[href="#mapa=MAP_ROUTE7"]').click();
  await p.locator('#detail .error').filter({ hasText: 'missing metatile 902' }).waitFor();
  await p.locator('#search').fill('New Bark Town');
  await p.locator('#list a').filter({ hasText: /^New Bark Town[0-9]/ }).click();
  await p.locator('#detail .links a').filter({ hasText: 'New Bark Town Lab' }).first().click();
  await p.locator('#meta').filter({ hasText: 'MAP_NEW_BARK_TOWN_LAB' }).waitFor();
  await p.locator('#game').selectOption('crystal');
  await p.locator('#source').filter({ hasText: 'Crystal' }).waitFor();
  await p.locator('#time').selectOption('nite');
  await p.waitForFunction(() => [...document.querySelectorAll('#stage img')].some(i => i.src.includes('/nite/')));
  await p.locator('#search').fill('New Bark Town');
  await p.locator('#list a').filter({ hasText: /^New Bark Town[0-9]/ }).click();
  await p.locator('#meta').filter({ hasText: 'NewBarkTown' }).waitFor();
  await p.locator('#detail .links a').filter({ hasText: 'Elms Lab' }).first().click();
  await p.locator('#meta').filter({ hasText: 'ElmsLab' }).waitFor();
  await p.locator('#game').selectOption('firered');
  await p.locator('#source').filter({ hasText: 'FireRed' }).waitFor();
  const restored = await p.locator('#viewport').evaluate(el => ({ x: el.scrollLeft, y: el.scrollTop }));
  assert(Math.abs(restored.x-knownPosition.x)<2 && Math.abs(restored.y-knownPosition.y)<2, 'source camera was not restored');
  assert(!requests.some(r => /\/src\/(core|games)\//.test(r)), 'common viewer loaded game engine');
  await ctx.shot('common-firered-desktop');
  await p.setViewportSize({ width: 390, height: 844 });
  await p.locator('#game').selectOption('hns');
  await p.locator('#source').filter({ hasText: 'Heart & Soul' }).waitFor();
  await p.locator('#world-btn').click();
  await p.locator('#meta').filter({ hasText: '77 mapas conectados' }).waitFor();
  await p.locator('#zoom').selectOption('0.5');
  await p.waitForFunction(() => { const images=[...document.querySelectorAll('#stage img')]; return images.length>0 && images.every(i => i.complete && i.naturalWidth>0) && images.every(i=>!i.src.includes('overview')); });
  await ctx.shot('common-hns-mobile');
  const mobile = await p.evaluate(() => ({ width: innerWidth, scroll: document.documentElement.scrollWidth, budget: document.querySelector('#budget').textContent }));
  assert(mobile.scroll <= mobile.width, 'mobile page overflows horizontally');
  assert(ctx.errors().length === 0, ctx.errors().join(';'));
  return { realUi: 'search, source switches, doors, back, drag, zoom LOD, Crystal night, unsupported HnS, desktop/mobile', noEngineRequests: true, restored, mobile };
}
