#!/usr/bin/env python3
"""Generate the per-move physical/special category table used by the "unified" battle rules profile.

Source of truth: pokeplatinum's move data (Gen 4, where the split is per move), extracted by
tools/refs/platinum_moves.py into refs/platinum/moves.json. It is cross-checked here against Pokémon Showdown's
Gen 4 categories (refs/showdown/gen_changes.json): the script fails if they disagree on any Gen 1-3 move.

Output: src/core/battle/data/moveCategoriesGen4.ts -- one character per Gen 3 move id
('P' physical, 'S' special, '-' status). Not edited by hand; regenerate with
    python3 tools/rules/move_categories.py

Usage: python3 tools/rules/move_categories.py [--check]   (--check fails if the committed file is stale)
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
PLATINUM = ROOT / "refs" / "platinum" / "moves.json"
SHOWDOWN = ROOT / "refs" / "showdown" / "gen_changes.json"
OUT = ROOT / "src" / "core" / "battle" / "data" / "moveCategoriesGen4.ts"
MOVES_COUNT = 355  # MOVES_COUNT in FireRed's constants: ids 0..354
LETTER = {"CLASS_PHYSICAL": "P", "CLASS_SPECIAL": "S", "CLASS_STATUS": "-"}
SD_LETTER = {"Physical": "P", "Special": "S", "Status": "-"}
# Names that differ between Platinum's data and Showdown's ids.
ALIASES = {"vicegrip": "visegrip", "hijumpkick": "highjumpkick", "smellingsalt": "smellingsalts",
           "faintattack": "feintattack"}


def norm(s: str) -> str:
    n = re.sub(r"[^a-z0-9]", "", s.lower())
    return ALIASES.get(n, n)


def build() -> tuple[str, dict]:
    plat = json.loads(PLATINUM.read_text())
    sd = json.loads(SHOWDOWN.read_text())
    pl = {m["id"]: m for m in plat["data"]}
    sdd = sd.get("data", sd)
    gen4: dict[str, str] = {}
    for key, rec in sdd["moves"].items():
        cat = rec["changes"].get("gen4", {}).get("category") or rec["gen3"].get("category")
        gen4[key] = SD_LETTER[cat]
    chars = ["-"]  # id 0 is MOVE_NONE
    disagreements = []
    for i in range(1, MOVES_COUNT):
        letter = LETTER[pl[i]["class"]]
        other = gen4.get(norm(pl[i]["name"]))
        if other is None:
            raise SystemExit(f"move {i} ({pl[i]['name']}) has no Showdown counterpart")
        if other != letter:
            disagreements.append((i, pl[i]["name"], letter, other))
        chars.append(letter)
    if disagreements:
        raise SystemExit(f"Platinum and Showdown disagree on {len(disagreements)} moves: {disagreements[:5]}")
    table = "".join(chars)
    meta = {"platinumCommit": plat["_meta"]["commit"], "showdownCommit": sd["_meta"]["commit"],
            "physical": table.count("P"), "special": table.count("S"), "status": table.count("-")}
    src = (
        "// GENERATED by tools/rules/move_categories.py -- do not edit; regenerate with that script.\n"
        f"// Source: pokeplatinum {meta['platinumCommit'][:10]} (res/moves/*/data.json via refs/platinum/moves.json),\n"
        f"// cross-checked against Pokémon Showdown {meta['showdownCommit'][:10]} Gen 4 categories (0 disagreements).\n"
        f"// One character per Gen 3 move id (0..{MOVES_COUNT - 1}): 'P' physical, 'S' special, '-' status.\n"
        f"// Counts: {meta['physical']} physical, {meta['special']} special, {meta['status']} status.\n"
        f"export const MOVE_CATEGORIES_GEN4 = \"{table}\";\n"
    )
    return src, meta


def main() -> int:
    src, meta = build()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != src:
            print("moveCategoriesGen4.ts is stale or missing; run tools/rules/move_categories.py")
            return 1
        print(f"moveCategoriesGen4.ts up to date ({meta})")
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(src)
    print(f"{OUT.relative_to(ROOT)}: {meta}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
