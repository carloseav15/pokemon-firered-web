#!/usr/bin/env python3
"""Extract the Fairy type label for the menu-info sheet from pokeemerald-expansion.

FireRed's sheet (gMenuInfoElements_Gfx) has a 32x12 label per type and none for Fairy. pokeemerald-expansion's
src/menu.c points Fairy at tile 0x04 of graphics/interface/menu_info.png, and its PNG has the label drawn there
(Heart & Soul's own sheet leaves that slot blank; Platinum, HeartGold and Crystal predate the type).

Source: ../refs-src/pokeemerald-expansion at the commit pinned in tools/refs/sources.json (fetch with
`npm run refs:fetch -- pokeemerald-expansion`; the sparse list includes graphics/interface/menu_info*).

Validation (the script fails otherwise):
  * the colours expansion's sheet assigns to palette indices 0..15 are FireRed's own (menu_info2.pal vs
    gMenuInfoElements2_Pal), so indices mean the same thing in both games;
  * the label only uses indices that already exist in FireRed's sheet palette;
  * its transparent pixels are the four rounded corners, like every other label.

The label is two-tone (index 5 above, 12 below), exactly as drawn upstream; it is copied unchanged.
Output: src/core/battle/data/fairyIcon.ts (4bpp tiles, 32x16 = 8 tiles, as BlitBitmapRect4Bit expects).
Needs Pillow to read the PNG.  Usage: python3 tools/rules/fairy_icon.py [--check] [--preview]
"""
from __future__ import annotations

import base64
import json
import re
import subprocess
import sys
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[2]
EXPANSION = ROOT.parent / "refs-src" / "pokeemerald-expansion"
PNG = EXPANSION / "graphics" / "interface" / "menu_info.png"
PAL2 = EXPANSION / "graphics" / "interface" / "menu_info2.pal"
OUT = ROOT / "src" / "core" / "battle" / "data" / "fairyIcon.ts"
FAIRY_TILE = 0x04  # [TYPE_FAIRY + 1] = { 32, 12, 0x4 } in expansion's src/menu.c
GLYPH = {0: " ", 5: "-", 12: "=", 14: "+", 15: "#"}  # preview: background top, background bottom, shadow, letters


def firered_palette2() -> list[int]:
    idx = json.loads((ROOT / "public/fr/incbin/index.json").read_text())
    pack, off, ln = idx["symbols"]["gMenuInfoElements2_Pal"]
    raw = (ROOT / f"public/fr/incbin/{pack}.bin").read_bytes()[off:off + ln]
    return [raw[i] | (raw[i + 1] << 8) for i in range(0, 32, 2)]


def expansion_palette2() -> list[int]:
    rows = PAL2.read_text().splitlines()[3:19]  # JASC-PAL: header, version, count, then 16 "r g b" lines
    out = []
    for line in rows:
        r, g, b = (int(v) for v in line.split())
        out.append((b >> 3) << 10 | (g >> 3) << 5 | (r >> 3))
    return out


def build() -> tuple[str, list[str], dict]:
    if not PNG.exists():
        raise SystemExit(f"{PNG} missing: run `npm run refs:fetch -- pokeemerald-expansion`")
    commit = subprocess.run(["git", "rev-parse", "HEAD"], cwd=EXPANSION, capture_output=True, text=True).stdout.strip()
    fr_pal, ex_pal = firered_palette2(), expansion_palette2()
    # Entry 0 is the transparent colour and is never shown; compare the visible entries.
    if fr_pal[1:] != ex_pal[1:]:
        raise SystemExit(f"palettes differ: FireRed {fr_pal} vs expansion {ex_pal}")
    im = Image.open(PNG)
    if im.size != (128, 128) or im.mode != "P":
        raise SystemExit(f"unexpected menu_info.png: {im.size} {im.mode}")
    x0, y0 = (FAIRY_TILE % 16) * 8, (FAIRY_TILE // 16) * 8
    grid = [[im.getpixel((x0 + x, y0 + y)) for x in range(32)] for y in range(12)]
    used = {v for row in grid for v in row}
    if not used <= set(GLYPH):
        raise SystemExit(f"label uses indices {sorted(used)}; expected a subset of {sorted(GLYPH)}")
    corners = [grid[0][0], grid[0][31], grid[11][0], grid[11][31]]
    transparent = sum(v == 0 for row in grid for v in row)
    if corners != [0, 0, 0, 0] or transparent != 4:
        raise SystemExit(f"label should have exactly its 4 corners transparent, has {transparent}")
    if any(v == 0 for v in grid[0][1:31]) or not any(v == 15 for row in grid for v in row):
        raise SystemExit("label has no body or no letters")
    # The four rows below the label (the cell is 32x16) must be empty in the source too.
    below = [im.getpixel((x0 + x, y0 + y)) for y in range(12, 16) for x in range(32)]
    if any(below):
        raise SystemExit("pixels below the label")

    data = bytearray(8 * 32)  # 32x16, tile order, low nibble first
    for y in range(12):
        for x in range(32):
            t = (y // 8) * 4 + x // 8
            a = t * 32 + (y % 8) * 4 + (x % 8) // 2
            data[a] |= grid[y][x] << (4 if (x % 8) & 1 else 0)
    preview = ["".join(GLYPH[v] for v in row) for row in grid]
    src = (
        "// GENERATED by tools/rules/fairy_icon.py -- do not edit; regenerate with that script.\n"
        "// Fairy type label for the menu-info sheet, copied from pokeemerald-expansion's graphics/interface/menu_info.png\n"
        f"// (tile 0x04, pinned commit {commit[:10]}). It is upstream's own drawing and keeps its two-tone background:\n"
        "// palette index 5 above and 12 below, indices FireRed's colour palette already defines.\n"
        "// Provenance: expansion added the label with its battle-engine sync; the checkout has no licence file and\n"
        "// CREDITS.md does not name the author. Review before redistributing.\n"
        "// 32x12 pixels in a 32x16, 4bpp tiled bitmap. Preview ('-' background top, '=' background bottom,\n"
        "// '#' letters, '+' shadow, ' ' transparent):\n"
        + "".join(f"//   |{row}|\n" for row in preview)
        + f"export const FAIRY_ICON_TILES_B64 = \"{base64.b64encode(bytes(data)).decode()}\";\n"
        "/** No palette entry is changed: the label only uses indices FireRed's colour palette already defines. */\n"
        "export const FAIRY_ICON_PALETTE_PATCH: { index: number; color: number } | null = null;\n"
    )
    return src, preview, {"commit": commit, "indices": sorted(used)}


def main() -> int:
    src, preview, meta = build()
    if "--preview" in sys.argv:
        print("\n".join(preview))
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != src:
            print("fairyIcon.ts is stale or missing; run tools/rules/fairy_icon.py")
            return 1
        print(f"fairyIcon.ts up to date ({meta})")
        return 0
    OUT.write_text(src)
    print(f"{OUT.relative_to(ROOT)} written ({meta})")
    if "--preview" not in sys.argv:
        print("\n".join(preview))
    return 0


if __name__ == "__main__":
    sys.exit(main())
